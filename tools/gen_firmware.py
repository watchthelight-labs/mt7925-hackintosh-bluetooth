"""Turn the MT7925 Bluetooth firmware in firmware/ into a C file the MtkBt kext links in.

  python3 tools/gen_firmware.py <out.c>

The blob comes from linux-firmware (mediatek/mt7925, commit d5455717ead0) and is
redistributable under LICENSES/LICENCE.mediatek. Its SHA-256 is checked against
firmware/SHA256SUMS and against the prefix pinned here, and embedded so the driver can
publish which firmware it carries.
"""
import hashlib
import sys
from pathlib import Path

FW = Path(__file__).resolve().parents[1] / "firmware"
BLOB = ("mtk_bt_fw", "BT_RAM_CODE_MT7925_1_1_hdr.bin")
PIN_PREFIX = "be7c18e37221e277"  # pinned here too, so a changed SHA256SUMS cannot slip a new blob in


def pinned():
    out = {}
    for line in (FW / "SHA256SUMS").read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if len(parts) == 2 and len(parts[0]) == 64:
            out[parts[1].lstrip("*")] = parts[0]
    return out


def main(dst):
    sums = pinned()
    sym, name = BLOB
    data = (FW / name).read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if sums.get(name) != digest:
        sys.exit(f"{name}: sha256 {digest} does not match firmware/SHA256SUMS")
    if not digest.startswith(PIN_PREFIX):
        sys.exit(f"{name}: sha256 {digest} does not start with the pinned prefix {PIN_PREFIX}")
    lines = ["// generated by tools/gen_firmware.py from firmware/, do not edit",
             "#include <stdint.h>",
             f"const unsigned int {sym}_len = {len(data)}u;",
             f'const char {sym}_sha256[] = "{digest}";',
             f'const char {sym}_name[] = "mediatek/mt7925/{name}";',
             f"const unsigned char {sym}[] __attribute__((aligned(16))) = {{"]
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    Path(dst).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{dst}: {name} {len(data)} bytes sha256 {digest}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
